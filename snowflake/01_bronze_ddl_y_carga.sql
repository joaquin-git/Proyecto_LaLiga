  ESTADIO VARCHAR,
  CIUDAD_ESTADIO VARCHAR,
  AFORO_ESTADIO VARCHAR,
  GOLES_LOCAL VARCHAR,
  GOLES_VISITANTE VARCHAR,
  RESULTADO VARCHAR,
  ESPECTADORES VARCHAR,
  ARBITRO VARCHAR,
  _FECHA_EXTRACCION VARCHAR,
  _FICHERO_ORIGEN VARCHAR,
  _FECHA_CARGA TIMESTAMP_NTZ
